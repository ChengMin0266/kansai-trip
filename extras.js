/* extras.js — DIY 2026-09-22：汇率换算器（记账页）+ 景点介绍弹窗（每日行程） */
(function () {
  "use strict";
  var $ = function (s, r) { return (r || document).querySelector(s); };

  /* ================= 汇率换算 ================= */
  var RKEY = "kansai_rates_v1", rates = null;
  try { rates = JSON.parse(localStorage.getItem(RKEY) || "null"); } catch (e) {}
  function fmt(n, d) { return n.toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d }); }

  function mountFx() {
    var root = $("#fx-root");
    if (!root) return;
    root.innerHTML = '<section class="fx-card">' +
      '<header class="fx-head"><div><p class="fx-kicker">CURRENCY</p><h2>汇率换算</h2></div>' +
      '<button type="button" class="fx-refresh" id="fx-btn">↻ 更新汇率</button></header>' +
      '<p class="fx-rate" id="fx-rate">–</p>' +
      '<div class="fx-row">' +
      '<label class="fx-cell"><span>日元 円</span><input id="fx-jpy" type="number" inputmode="decimal" placeholder="输入日元"></label>' +
      '<div class="fx-cell"><span>人民币 ¥</span><output id="fx-cny">–</output></div>' +
      '<div class="fx-cell"><span>英镑 £</span><output id="fx-gbp">–</output></div>' +
      '</div></section>';
    $("#fx-btn").addEventListener("click", fetchRates);
    $("#fx-jpy").addEventListener("input", convert);
    renderRates();
    if (!rates || Date.now() - rates.ts > 6 * 3600 * 1000) { if (navigator.onLine !== false) fetchRates(); }
  }
  function renderRates() {
    var el = $("#fx-rate");
    if (!el) return;
    if (!rates) { el.textContent = "尚未获取汇率，点「更新汇率」"; convert(); return; }
    el.textContent = "100 円 ≈ " + fmt(rates.cny * 100, 2) + " 人民币 · " + fmt(rates.gbp * 100, 3) + " 英镑 · 更新于 " +
      new Date(rates.ts).toLocaleString("zh-CN", { month: "numeric", day: "numeric", hour: "2-digit", minute: "2-digit" });
    convert();
  }
  function saveRates(c, g) { rates = { cny: c, gbp: g, ts: Date.now() }; try { localStorage.setItem(RKEY, JSON.stringify(rates)); } catch (e) {} renderRates(); }
  function fetchRates() {
    var btn = $("#fx-btn"); if (btn) btn.textContent = "…";
    fetch("https://open.er-api.com/v6/latest/JPY").then(function (r) { return r.json(); })
      .then(function (j) { if (j && j.rates && j.rates.CNY && j.rates.GBP) { saveRates(j.rates.CNY, j.rates.GBP); } else { throw 0; } })
      .catch(function () {
        return fetch("https://api.frankfurter.app/latest?from=JPY&to=CNY,GBP").then(function (r) { return r.json(); })
          .then(function (j) { if (j && j.rates && j.rates.CNY && j.rates.GBP) saveRates(j.rates.CNY, j.rates.GBP); })
          .catch(function () { var el = $("#fx-rate"); if (el) el.textContent = "获取失败（离线？），沿用上次汇率"; });
      })
      .then(function () { if (btn) btn.textContent = "↻ 更新汇率"; });
  }
  function convert() {
    var i = $("#fx-jpy"); if (!i) return;
    var v = parseFloat(i.value);
    $("#fx-cny").textContent = (!rates || isNaN(v)) ? "–" : "¥ " + fmt(v * rates.cny, 2);
    $("#fx-gbp").textContent = (!rates || isNaN(v)) ? "–" : "£ " + fmt(v * rates.gbp, 2);
  }

  /* ================= 景点介绍弹窗 ================= */
  var NAMES = Object.keys(SPOTS).map(function (k) {
    var short = SPOTS[k].name.split("（")[0].split("・")[0].split("·")[0].trim();
    return [k, short || SPOTS[k].name];
  }).sort(function (a, b) { return b[1].length - a[1].length; });

  function wrapTimeline() {
    var box = $("#timeline"); if (!box) return;
    box.querySelectorAll(".day-detail li, .day-detail p, .day-detail span, .day-detail div").forEach(function (el) {
      if (el.children.length || el.dataset.poiDone) return;
      var text = el.textContent; if (!text || text.length < 2) return;
      var hit = NAMES.some(function (pair) { return text.indexOf(pair[1]) >= 0; });
      if (!hit) return;
      var html = el.innerHTML;
      NAMES.forEach(function (pair) {
        var key = pair[0], name = pair[1];
        if (html.indexOf(name) < 0 || html.indexOf('data-poi="' + key + '"') >= 0) return;
        html = html.replace(name, '<button type="button" class="poi-link" data-poi="' + key + '">' + name + "</button>");
      });
      el.innerHTML = html;
      el.dataset.poiDone = "1";
    });
  }
  function ensureDialog() {
    var dlg = $("#poi-dialog");
    if (dlg) return dlg;
    dlg = document.createElement("dialog");
    dlg.id = "poi-dialog"; dlg.className = "poi-dialog";
    dlg.innerHTML = '<button type="button" class="poi-close" aria-label="关闭">×</button><div id="poi-body"></div>';
    document.body.appendChild(dlg);
    dlg.querySelector(".poi-close").addEventListener("click", function () { dlg.close(); });
    dlg.addEventListener("click", function (e) { if (e.target === dlg) dlg.close(); });
    return dlg;
  }
  function showPoi(key) {
    var s = SPOTS[key]; if (!s) return;
    var dlg = ensureDialog();
    $("#poi-body").innerHTML = '<p class="poi-tag">' + (s.jp || "") + (s.tag ? " · " + s.tag : "") + "</p>" +
      "<h3>" + s.name + "</h3><p class='poi-intro'>" + s.intro + "</p>" +
      "<ul>" + (s.pts || []).map(function (p) { return "<li>" + p + "</li>"; }).join("") + "</ul>" +
      (s.tip ? "<p class='poi-tip'>💡 " + s.tip + "</p>" : "");
    dlg.showModal();
  }
  document.addEventListener("click", function (e) {
    var b = e.target.closest("[data-poi]");
    if (b) { e.preventDefault(); showPoi(b.dataset.poi); }
  });

  function boot() {
    mountFx();
    wrapTimeline();
    var box = $("#timeline");
    if (box && window.MutationObserver) {
      var pending = null;
      new MutationObserver(function () {
        if (pending) return;
        pending = setTimeout(function () { pending = null; wrapTimeline(); }, 120);
      }).observe(box, { childList: true, subtree: true });
    }
  }
  if (document.readyState === "loading") { document.addEventListener("DOMContentLoaded", function () { setTimeout(boot, 300); }); }
  else { setTimeout(boot, 300); }
})();
